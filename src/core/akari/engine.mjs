function detectStartCamp(x, y) {
  const camps = [...BLUE_SIDE_CAMPS, ...RED_SIDE_CAMPS];
  let minDist = Infinity;
  let nearest = camps[0];
  for (const c of camps) {
    const dx = x - c.x;
    const dy = y - c.y;
    const dist = dx * dx + dy * dy;
    if (dist < minDist) {
      minDist = dist;
      nearest = c;
    }
  }
  return { camp: nearest.camp, side: nearest.side };
}
