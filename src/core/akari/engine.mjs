function standardize(numbers) {
  if (numbers.length === 0) return [];
  const min = Math.min(...numbers);
  const max = Math.max(...numbers);
  const range = max - min;
  if (range === 0) {
    return new Array(numbers.length).fill(0);
  }
  return numbers.map((num) => (num - min) / range);
}
function percentile(sorted, p) {
  if (sorted.length === 0) {
    return 0;
  }
  const index = p * (sorted.length - 1);
  const lower = Math.floor(index);
  const fraction = index - lower;
  if (lower === sorted.length - 1) {
    return sorted[lower];
  }
  return sorted[lower] + fraction * (sorted[lower + 1] - sorted[lower]);
}
function findOutliersByIqr(data, keyGetter, threshold = 1.5) {
  if (!keyGetter) {
    keyGetter = (value) => value;
  }
  const sorted = data.slice().sort((a, b) => keyGetter(a) - keyGetter(b));
  const q1 = percentile(sorted.map(keyGetter), 0.25);
  const q3 = percentile(sorted.map(keyGetter), 0.75);
  const iqr = q3 - q1;
  const lowerBound = q1 - threshold * iqr;
  const upperBound = q3 + threshold * iqr;
  const below = [];
  const over = [];
  for (const d of data) {
    if (keyGetter(d) < lowerBound) {
      below.push(d);
    } else if (keyGetter(d) > upperBound) {
      over.push(d);
    }
  }
  return {
    below,
    over
  };
}

// akari:src/shared/data-adapter/match-history/win-result.ts
function computeWinResult(endOfGameResult, participant) {
  if (endOfGameResult && endOfGameResult.startsWith("Abort_")) {
    return { isSurrender: false, result: "abort" };
  }
  if (participant.gameEndedInEarlySurrender) {
    return { isSurrender: true, result: "remake" };
  }
  if (participant.teamEarlySurrendered) {
    return { isSurrender: true, result: "loss" };
  }
  if (participant.win) {
    return { isSurrender: false, result: "win" };
  } else {
    return { isSurrender: participant.gameEndedInSurrender, result: "loss" };
  }
}

