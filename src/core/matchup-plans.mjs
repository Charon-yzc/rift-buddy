export function publicMatchupOpponent(data,ids,targetId){
 if(!targetId||!Array.isArray(ids)||!ids.includes(targetId))return null;
 return data?.champions?.find(c=>c.id===targetId)||null;
}
export function matchupTargetKey(selection){return [selection?.id,selection?.role,selection?.mode,selection?.comboId||''].join(':');}

