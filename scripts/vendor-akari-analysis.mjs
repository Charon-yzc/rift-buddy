// Reproduce the dependency-free Akari engine from immutable Git objects, not the working tree.
import {execFileSync} from 'node:child_process';
import {createHash} from 'node:crypto';
import {mkdir,writeFile} from 'node:fs/promises';
import {createRequire} from 'node:module';
import path from 'node:path';
import {fileURLToPath} from 'node:url';

const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const source=path.resolve(process.argv[2]||path.join(root,'..','league-akari-party'));
const revision='60f1584c';
const commit=execFileSync('git',['rev-parse',`${revision}^{commit}`],{cwd:source,encoding:'utf8'}).trim();
const requireSource=createRequire(path.join(source,'package.json'));
const {build,version:esbuildVersion}=requireSource('esbuild');
const sha256=bytes=>createHash('sha256').update(bytes).digest('hex');
const originals=new Map();
function original(name){
  if(!originals.has(name))originals.set(name,execFileSync('git',['show',`${commit}:${name}`],{cwd:source,maxBuffer:8*1024*1024}));
  return originals.get(name).toString('utf8');
}
const license=original('LICENSE').replace(/\r\n/g,'\n');
const adaptations=[
  {file:'src/shared/data-adapter/analysis/player/single/objectives.ts',reason:'Remove participant-ID 1–5 team guessing. The bridge resolves absent killerTeamId from verified roster team IDs; unresolved objective teams are skipped and objective availability is false.'},
  {file:'src/shared/data-adapter/analysis/player/single/jungle.ts',reason:'Skip champion kill positions that are absent instead of dereferencing null. The bridge marks position-dependent jungle metrics unavailable when relevant coordinates are missing.'},
  {file:'src/shared/constants/common.ts',reason:'Omit unused API URL re-exports so the pure relationship module does not pull application network configuration into the bundle. EMPTY_PUUID remains verbatim.'}
];
const entry=`
export {analyzeGames,analyzeGame,computeSingleAkariScore,computeAggregatedAkariScore} from '@shared/data-adapter/analysis/player/index';
export {analyzePlayers} from '@shared/data-adapter/analysis/team/index';
export {analyzeRelationship} from '@shared/data-adapter/analysis/relationship/index';
export {findOutliersByIqr} from '@shared/data-adapter/utils';
export * from '@shared/utils/team-up-calc';
`;
const result=await build({
  stdin:{contents:entry,resolveDir:source,sourcefile:'akari-entry.ts',loader:'ts'},
  bundle:true,format:'esm',platform:'neutral',target:'es2022',write:false,metafile:true,
  treeShaking:true,legalComments:'inline',charset:'utf8',
  banner:{js:`/*\nVendored from League Akari ${commit}.\nGenerated by scripts/vendor-akari-analysis.mjs. See manifest.json for source hashes and adaptations.\n\n${license.trim()}\n*/`},
  plugins:[{name:'immutable-akari-source',setup(plugin){
    plugin.onResolve({filter:/.*/},args=>{
      let name;
      if(args.path.startsWith('@shared/'))name=`src/shared/${args.path.slice(8)}`;
      else if(args.path.startsWith('.')&&args.namespace==='akari')name=path.posix.normalize(path.posix.join(path.posix.dirname(args.importer),args.path));
      else throw Error(`Unexpected runtime dependency: ${args.path}`);
      if(!name.startsWith('src/shared/'))throw Error(`Source path outside pure shared modules: ${name}`);
      if(!path.posix.extname(name))name+='.ts';
      return {path:name,namespace:'akari'};
    });
    plugin.onLoad({filter:/.*/,namespace:'akari'},args=>{
      let contents=original(args.path);
      if(args.path==='src/shared/constants/common.ts')contents=contents.replace(/export \{[\s\S]*?\} from '@shared\/shards\/akari-api'/,'');
      if(args.path.endsWith('/single/objectives.ts')){
        const unsafe='event.killerTeamId ?? (event.killerId >= 1 && event.killerId <= 5 ? 100 : 200)';
        if(!contents.includes(unsafe))throw Error('Upstream objective adaptation no longer matches');
        contents=contents.replace(unsafe,'event.killerTeamId ?? null').replace('const isOurTeam = killerTeam === participant.teamId','if (killerTeam === null) continue\n      const isOurTeam = killerTeam === participant.teamId');
      }
      if(args.path.endsWith('/single/jungle.ts')){
        const check="if (event.type !== 'CHAMPION_KILL') continue";
        if(contents.split(check).length!==3)throw Error('Upstream jungle adaptation no longer matches');
        contents=contents.replaceAll(check,`${check}\n      if (!event.position) continue`);
      }
      return {contents,loader:'ts'};
    });
  }}]
});
if(Object.values(result.metafile.outputs).some(output=>output.imports.length))throw Error('Vendored engine contains external imports');
const output=path.join(root,'src','core','akari');
await mkdir(output,{recursive:true});
const engine=result.outputFiles[0].contents;
await writeFile(path.join(output,'engine.mjs'),engine);
await writeFile(path.join(output,'LICENSE.akari.txt'),license);
const manifest={
  project:'League Akari',repository:'https://github.com/LeagueAkari/LeagueAkari',revision,commit,
  license:'MIT',copyright:'Copyright (c) 2026 Hanxven',
  generator:'node scripts/vendor-akari-analysis.mjs [path-to-league-akari-party]',
  esbuildVersion,engineSha256:sha256(engine),adaptations,
  bridgeSemantics:[
    'Canonical SGP wrappers are reconstructed only from the normalized whitelist. No raw source object is retained.',
    'Original numeric defaults are internal only. Missing dependencies null the affected single, aggregate and champion metrics. availability records metric sample counts and timeline limitations.',
    'Timeline total CS is placed in a synthetic minionsKilled slot with jungleMinionsKilled=0 solely for the original total-CS calculation. The real split remains unknown and is never exposed as measured.',
    'Original jungle geometry, minute sampling and gank heuristics are historical inference; they do not prove player intent.',
    'Undefined zero-mean CV sentinels and non-finite team BSI are exposed as null. Historical inference is bounded to 16 visible identities because the original utility enumerates every subset.',
    'Historical groups use original pairwise minimum together counts, not proof of a premade party or exact all-player simultaneous games. Caller supplies region/source-scoped identity; Arena is grouped by own subteam.',
    'Input history must belong to one query target and one caller-managed source/region scope. Duplicate game IDs are counted once; mixed query targets throw.'
  ],
  sources:[...originals].sort(([a],[b])=>a.localeCompare(b,'en')).map(([file,bytes])=>({file,sha256:sha256(bytes)}))
};
await writeFile(path.join(output,'manifest.json'),JSON.stringify(manifest,null,2)+'\n');
console.log(`Vendored ${manifest.sources.length} immutable source files (${engine.length} bytes), SHA-256 ${manifest.engineSha256}`);
